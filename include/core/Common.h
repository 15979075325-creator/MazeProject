// 本文件要做什么：
//   1. 定义坐标类型 Pos = (row, col)，行优先，从 0 开始计数
//   2. 定义迷宫矩阵类型 Grid，grid[r][c] 存放一个字符：
//        '#' 墙   ' ' 通路   'S' 起点   'E' 终点   '.' 路径高亮
//   3. 所有模块（生成器/求解器/渲染/IO）都 include 本文件，
//      保证两人开发时类型完全一致（见 docs/interface.md §2）
// 注意：本文件只放类型别名，不放任何实现，避免重复链接问题
// ============================================================

#include <vector>
#include <utility>

// 坐标：(row, col) 行优先。pos.first = 行，pos.second = 列
using Pos  = std::pair<int, int>;

// 迷宫矩阵：Grid[行][列]
using Grid = std::vector<std::vector<char>>;
